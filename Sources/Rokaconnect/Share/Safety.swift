import Foundation
import AppKit
import CoreServices

/// Small security helpers shared by everything that receives data from other devices.
enum Safety {
    /// Marks a received file as "downloaded", like Safari does. macOS then checks it with Gatekeeper and shows
    /// its usual warning before an app or script from it can run.
    static func quarantine(_ url: URL, from peer: String) {
        let props: [String: Any] = [
            kLSQuarantineAgentNameKey as String: "Rokaconnect",
            kLSQuarantineTypeKey as String: kLSQuarantineTypeOtherDownload as String,
            kLSQuarantineOriginURLKey as String: URL(string: "rokaconnect://\(peer.addingPercentEncoding(withAllowedCharacters: .urlHostAllowed) ?? "device")") as Any,
        ]
        try? (url as NSURL).setResourceValue(props, forKey: .quarantinePropertiesKey)
    }

    /// True when the clipboard holds something a password manager marked as private (nspasteboard.org convention):
    /// a password, a one-time code, or other concealed/temporary data. Such items are never synced.
    static func clipboardIsPrivate(_ pb: NSPasteboard = .general) -> Bool {
        let marks = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
                     "com.agilebits.onepassword", "com.typeit4me.clipping"]
        let types = pb.types?.map(\.rawValue) ?? []
        return types.contains { marks.contains($0) }
    }

    /// Biggest total a Quick Share sender may deliver in one go (also caps a single file).
    static let maxQuickShareBytes: Int64 = 20 * 1024 * 1024 * 1024     // 20 GB
    /// Biggest text a Quick Share sender may deliver.
    static let maxQuickShareText = 1_000_000
}

/// Remembers recently seen Portal message nonces so a captured message can't be sent again (replay).
/// Messages are already only accepted within 120 s of their timestamp, so 130 s of memory is enough.
final class ReplayGuard {
    static let shared = ReplayGuard()
    private var seen: [Data: Date] = [:]
    private let lock = NSLock()

    /// Returns false if this nonce was already used (a replay).
    func firstUse(_ nonce: Data) -> Bool {
        lock.lock(); defer { lock.unlock() }
        let now = Date()
        if seen.count > 512 { seen = seen.filter { now.timeIntervalSince($0.value) < 130 } }
        if let t = seen[nonce], now.timeIntervalSince(t) < 130 { return false }
        seen[nonce] = now
        return true
    }
}
